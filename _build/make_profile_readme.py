#!/usr/bin/env python3
"""Emit the GitHub profile README for github.com/ankit-ai from the site's own data.

github.com/<user> renders GitHub's profile page, not arbitrary HTML, so the site
itself cannot live there. The one piece of that page under our control is the
profile README, which is Markdown in the repo <user>/<user>. This script generates
that Markdown from site.json, papers.json and content.json, the same three files
build.py reads, so the profile and the site state the same facts.

Every paper link points at the canonical site page rather than at arXiv or the ACL
Anthology. That is deliberate: those pages carry the citation_* metadata Scholar
indexes, and the profile is a high-traffic entry point into them.

Usage:
    python3 _build/make_profile_readme.py                     # -> _work/profile-README.md
    python3 _build/make_profile_readme.py --out ../path/README.md
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def load(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return json.load(fh)


def venue_line(p):
    """Venue as the site states it.

    accepted_note is deliberately NOT appended. On the paper page it is a full
    sentence explaining why an accepted paper still cites the arXiv version, which
    is right there and wrong in a one-line list entry.
    """
    return p.get("venue_short") or p.get("venue_long") or ""


def paper_entry(p, content, base_url):
    slug = p["slug"]
    url = "%s/papers/%s/" % (base_url.rstrip("/"), slug)
    tldr = (content.get(slug, {}).get("tldr") or "").strip()
    # Venue is set off with a period rather than parentheses because several
    # venue_short values already contain parentheses and would nest.
    out = ["- **[%s](%s)**. %s." % (p["title"], url, venue_line(p).rstrip("."))]
    if tldr:
        out.append(" %s" % tldr)
    return "".join(out)


def build(site, papers, content):
    base = site["base_url"]
    name = site["name"]
    lines = []
    A = lines.append

    A("### Hello, I am %s" % name.split()[0])
    A("")
    A("%s" % site["bio"][0])
    A("")
    A("**Papers, with full abstracts and PDFs: [%s](%s/)**"
      % (base.replace("https://", ""), base))
    A("")
    A("- I work in Applied Science at Amazon on grounded reasoning for AI agents,")
    A("  agent memory, and web-scale retrieval across text, images and structured data.")
    A("- I have served as a consultant and course facilitator for Stanford's XCS221")
    A("  (Principles of AI), XCS224N and XCS224U (Natural Language Understanding).")
    A("- I mentor and collaborate with builders working on frontier AI. If you have an")
    A("  idea that lines up with what I work on, reach out.")
    A("- Reach me at %s" % site["email_display"])
    A("")
    A("---")
    A("")

    A("### What I work on")
    A("")
    for t in site["themes"]:
        A("- **%s.** %s" % (t["heading"].rstrip("."), t["body"]))
    A("")
    A("---")
    A("")

    peer = [p for p in papers["papers"] if not p.get("is_preprint")]
    pre = [p for p in papers["papers"] if p.get("is_preprint")]

    A("### Publications")
    A("")
    A("Peer reviewed, most recent first. Every link opens the paper's own page with the")
    A("complete abstract, the key results, and the PDF.")
    A("")
    for p in peer:
        A(paper_entry(p, content, base))
    A("")
    A("Preprints.")
    A("")
    for p in pre:
        A(paper_entry(p, content, base))
    A("")
    A("Earlier undergraduate work in signal processing, image processing and")
    A("steganography is listed on the [publications page](%s/publications/)." % base)
    A("")
    A("---")
    A("")

    if papers.get("patents"):
        A("### Patents")
        A("")
        for pt in papers["patents"]:
            A("- **[%s](%s)**, %s. %s, granted %s."
              % (pt["title"], pt["url"], pt["number"], pt["assignee"], pt["granted"]))
        A("")
        A("---")
        A("")

    A("### Elsewhere")
    A("")
    # Skip the GitHub link: this file renders ON the GitHub profile, so it would
    # link the reader to the page they are already looking at.
    for l in site["links"]:
        if "github.com" in l["url"]:
            continue
        A("- [%s](%s)" % (l["label"], l["url"]))
    A("")
    A("<!-- Generated by _build/make_profile_readme.py from _build/site.json,")
    A("     _build/papers.json and _build/content.json. Do not hand-edit: edit the")
    A("     JSON in the ankit-ai.github.io repo and regenerate, so the profile and")
    A("     the site never disagree. -->")

    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "_work", "profile-README.md"))
    args = ap.parse_args()

    site = load("site.json")
    papers = load("papers.json")
    content = load("content.json")

    md = build(site, papers, content)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(md)

    n_peer = len([p for p in papers["papers"] if not p.get("is_preprint")])
    n_pre = len(papers["papers"]) - n_peer
    print("wrote %s" % args.out)
    print("  %d peer reviewed, %d preprints, %d patents, %d themes, %d links"
          % (n_peer, n_pre, len(papers.get("patents", [])),
             len(site["themes"]), len(site["links"])))


if __name__ == "__main__":
    main()
